const DISPLAY_TIME_ZONE = "America/New_York";

export function ashevilleDailyNormals(value = Date.now()) {
  const key = normalDateKey(value);
  const normals = key ? NORMALS_BY_DATE[key] : null;
  if (!normals) return null;

  return {
    high: normals[0],
    low: normals[1],
    period: "1991-2020",
    station: "Asheville Regional Airport (USW00003812)"
  };
}

function normalDateKey(value) {
  if (typeof value === "string") {
    const match = value.match(/^\d{4}-(\d{2}-\d{2})/);
    if (match) return match[1];
  }

  const timestamp = value instanceof Date ? value.getTime() : Number(value);
  if (!Number.isFinite(timestamp)) return null;
  const parts = new Intl.DateTimeFormat("en-US", {
    month: "2-digit",
    day: "2-digit",
    timeZone: DISPLAY_TIME_ZONE
  }).formatToParts(new Date(timestamp));
  const fields = Object.fromEntries(parts.map((part) => [part.type, part.value]));
  return fields.month && fields.day ? `${fields.month}-${fields.day}` : null;
}
